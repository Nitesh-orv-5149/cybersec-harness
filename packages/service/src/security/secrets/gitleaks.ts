// Gitleaks adapter: argument building, the generated config (Gitleaks defaults or the project's own
// .gitleaks.toml, plus the workbench's excluded directories) and the JSON report reader.
// Gitleaks always runs with --redact, so the report on disk and everything stored in MongoDB carries
// "REDACTED" in place of the secret value. The parser re-checks that and drops any field that still holds it.
import fs from 'node:fs';
import path from 'node:path';
import { redact } from '../../util.js';
import type { ScanObservation } from '../scan/types.js';

/** Gitleaks uses this exit code when it found leaks; 0 means none; anything else is an error. */
export const LEAKS_EXIT_CODE = 42;

export function parseGitleaksVersion(s: string): string | null {
  return s.trim().match(/^v?(\d+\.\d+\.\d+)/m)?.[1] ?? null;
}

/** `gitleaks dir` exists from 8.19.0; earlier versions only have `detect`. */
export function supportsDirCommand(version: string): boolean {
  const [a, b] = version.split('.').map(Number);
  return a! > 8 || (a === 8 && b! >= 19);
}

const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** Config written into the run directory. Extends the project's own .gitleaks.toml when there is one. */
export function gitleaksConfig(root: string, exclude: string[]): { toml: string; base: string } {
  const own = path.join(root, '.gitleaks.toml');
  const hasOwn = fs.existsSync(own);
  const lines = ['# generated by the workbench for this run', '[extend]', hasOwn ? `path = '''${own}'''` : 'useDefault = true', ''];
  if (exclude.length) {
    lines.push('[allowlist]', 'description = "directories excluded in workbench.config.json (security.secrets.exclude)"');
    lines.push(`paths = [${exclude.map((d) => `'''(^|/)${escapeRe(d)}(/|$)'''`).join(', ')}]`, '');
  }
  return { toml: lines.join('\n'), base: hasOwn ? '.gitleaks.toml (project)' : 'Gitleaks default rules' };
}

export function gitleaksArgs(o: { mode: 'workspace' | 'history'; configPath: string; reportPath: string; maxTargetMegabytes: number }): string[] {
  return [
    o.mode === 'history' ? 'git' : 'dir', '.',
    '--config', o.configPath,
    '--report-format', 'json', '--report-path', o.reportPath,
    '--redact', '--no-banner', '--no-color', '--log-level', 'info',
    '--exit-code', String(LEAKS_EXIT_CODE),
    '--max-target-megabytes', String(o.maxTargetMegabytes),
  ];
}

/** "scanned ~26283 bytes (26.28 KB) in 666ms" from the log on stderr. */
export function scannedBytes(stderr: string): number | null {
  const m = stderr.match(/scanned ~(\d+) bytes/);
  return m ? Number(m[1]) : null;
}

interface GitleaksFinding {
  RuleID: string; Description?: string; File: string; SymlinkFile?: string;
  StartLine: number; EndLine: number; StartColumn: number; EndColumn: number;
  Match?: string; Secret?: string; Entropy?: number; Fingerprint?: string; Tags?: string[];
  Commit?: string; Date?: string; Author?: string; Email?: string; Message?: string;
}

/** With --redact the secret is the literal marker and the match keeps only its surrounding context. */
const secretRedacted = (s: string | undefined) => !s || s.trim() === 'REDACTED';
const matchRedacted = (s: string | undefined) => !s || s.includes('REDACTED');

export function readGitleaksReport(text: string, opts: { toolVersion: string | null; mode: 'workspace' | 'history' }):
  { observations: ScanObservation[]; unredacted: number } | { error: string } {
  let data: unknown;
  try { data = JSON.parse(text); } catch (e) { return { error: `Gitleaks report is not valid JSON: ${(e as Error).message}` }; }
  if (!Array.isArray(data)) return { error: 'Gitleaks report is not a JSON array' };
  let unredacted = 0;
  const observations: ScanObservation[] = [];
  for (const raw of data as GitleaksFinding[]) {
    if (!raw || typeof raw.RuleID !== 'string' || typeof raw.File !== 'string') return { error: 'Gitleaks report has an entry without RuleID/File' };
    const file = raw.File.replace(/\\/g, '/').replace(/^\.\//, '');
    const commit = opts.mode === 'history' && raw.Commit ? raw.Commit : undefined;
    // Defence in depth: if the value is somehow not redacted, it is never stored.
    const safe = secretRedacted(raw.Secret) && matchRedacted(raw.Match);
    if (!safe) unredacted++;
    const where = `${file}:${raw.StartLine}${commit ? ` @ ${commit.slice(0, 12)}` : ''}`;
    observations.push({
      tool: 'gitleaks', toolVersion: opts.toolVersion, ruleId: raw.RuleID, ruleName: raw.Description ? null : raw.RuleID,
      title: `Possible secret (${raw.RuleID}) in ${where}`,
      message: raw.Description ?? null,
      // Gitleaks assigns no severity. A credential in the code is treated as high until someone confirms it is a dummy value.
      severity: 'high', originalSeverity: null, confidence: null,
      cwe: ['CWE-798'], references: [],
      location: { file, line: raw.StartLine, endLine: raw.EndLine, ...(commit ? { commit } : {}) },
      evidence: {
        rule: raw.RuleID, description: raw.Description ?? null,
        lines: `${raw.StartLine}-${raw.EndLine}`, columns: `${raw.StartColumn}-${raw.EndColumn}`,
        match: safe ? redact(raw.Match ?? '') : '[withheld: value was not redacted by the tool]',
        entropy: typeof raw.Entropy === 'number' ? Math.round(raw.Entropy * 100) / 100 : null,
        fingerprint: raw.Fingerprint ?? null, tags: raw.Tags ?? [],
        ...(raw.SymlinkFile ? { symlinkFile: raw.SymlinkFile } : {}),
        ...(commit ? { commit, commitDate: raw.Date ?? null } : {}),
      },
      dedupeKey: `secret|${file}|${raw.StartLine}|${raw.RuleID}|${commit ?? 'worktree'}`,
      ids: [`gitleaks:${raw.RuleID}`, 'CWE-798'],
    });
  }
  return { observations, unredacted };
}

/** The copy of the report that is kept: secret and match fields replaced unless they are already redacted; author e-mail removed. */
export function sanitizeGitleaksReport(text: string): string {
  try {
    const data = JSON.parse(text) as GitleaksFinding[];
    if (!Array.isArray(data)) return '[]';
    return JSON.stringify(data.map((f) => ({
      ...f,
      Secret: secretRedacted(f.Secret) ? f.Secret : 'REDACTED',
      Match: matchRedacted(f.Match) ? f.Match : 'REDACTED',
      Email: f.Email ? '[removed]' : f.Email,
    })), null, 2);
  } catch { return '[]'; }
}
